/**
 * @file nrf_modem_at_wrapper.c
 * Wrapper for nrf_modem_at_cmd to route AT#XPING to its handler and to fake the
 * AT+CGPADDR response that util_get_ip_addr() reads the local address from.
 */

#include <string.h>
#include <strings.h>
#include <stdarg.h>
#include <errno.h>
#include <stdio.h>
#include <nrf_modem_at.h>

/* Response to AT+CGPADDR, set by the test. NULL makes the command fail. */
const char *test_cgpaddr_response;

/* CMock-generated internal function for handling mock expectations.
 * Not in header because CMock doesn't generate declarations for variadic functions.
 */
extern int __cmock_nrf_modem_at_cmd(void *buf, size_t len, const char *fmt, ...);

/* Generated by SM_AT_CMD_CUSTOM() */
extern int handle_at_icmp_ping_wrapper_xping(char *buf, size_t len, char *at_cmd);

int nrf_modem_at_cmd(void *buf, size_t buf_size, const char *fmt, ...)
{
	va_list args;
	char at_cmd[256];
	int ret;

	va_start(args, fmt);
	ret = vsnprintf(at_cmd, sizeof(at_cmd), fmt, args);
	va_end(args);

	if (ret < 0 || ret >= (int)sizeof(at_cmd)) {
		return -EINVAL;
	}

	if (strncasecmp(at_cmd, "AT#XPING", 8) == 0) {
		return handle_at_icmp_ping_wrapper_xping((char *)buf, buf_size, at_cmd);
	}

	if (strncmp(at_cmd, "AT+CGPADDR", 10) == 0) {
		if (test_cgpaddr_response == NULL) {
			return -EINVAL;
		}
		snprintf(buf, buf_size, "%s", test_cgpaddr_response);
		return 0;
	}

	return __cmock_nrf_modem_at_cmd(buf, buf_size, "%s", at_cmd);
}
